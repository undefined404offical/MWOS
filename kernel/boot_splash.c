static void splash_draw_char(int x, int y, char c, uint32_t color) {
    if (!g_framebuffer || !g_backbuffer)
        return;
    if (c < 32 || c > 126)
        return;

    uint32_t* bb = g_backbuffer;
    uint32_t pitch = g_backbuffer_pitch;
    uint32_t sw = g_framebuffer->framebuffer_width;
    uint32_t sh = g_framebuffer->framebuffer_height;

    int idx = (c - 32) * 8;
    for (int row = 0; row < 8; row++) {
        uint8_t bits = font_8x8[idx + row];
        int sy = y + row;
        if (sy < 0 || sy >= (int)sh)
            continue;
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                int sx = x + col;
                if (sx >= 0 && sx < (int)sw) {
                    bb[sy * pitch + sx] = color;
                }
            }
        }
    }
}

static void splash_draw_text(int x, int y, const char* text, uint32_t color) {
    int cx = x;
    while (*text) {
        splash_draw_char(cx, y, *text, color);
        cx += 8;
        text++;
    }
}

static void splash_fill_rect(int x, int y, int w, int h, uint32_t color) {
    if (!g_framebuffer || !g_backbuffer)
        return;
    uint32_t* bb = g_backbuffer;
    uint32_t pitch = g_backbuffer_pitch;
    uint32_t sw = g_framebuffer->framebuffer_width;
    uint32_t sh = g_framebuffer->framebuffer_height;

    for (int yy = 0; yy < h; yy++) {
        int sy = y + yy;
        if (sy < 0 || sy >= (int)sh)
            continue;
        for (int xx = 0; xx < w; xx++) {
            int sx = x + xx;
            if (sx >= 0 && sx < (int)sw) {
                bb[sy * pitch + sx] = color;
            }
        }
    }
}

static void splash_draw_rect_outline(int x, int y, int w, int h,
                                     uint32_t color) {
    if (!g_framebuffer || !g_backbuffer)
        return;
    uint32_t* bb = g_backbuffer;
    uint32_t pitch = g_backbuffer_pitch;
    uint32_t sw = g_framebuffer->framebuffer_width;
    uint32_t sh = g_framebuffer->framebuffer_height;

    for (int i = 0; i < w; i++) {
        int sx = x + i;
        if (sx >= 0 && sx < (int)sw) {
            if (y >= 0 && y < (int)sh)
                bb[y * pitch + sx] = color;
            if (y + h - 1 >= 0 && y + h - 1 < (int)sh)
                bb[(y + h - 1) * pitch + sx] = color;
        }
    }
    for (int i = 0; i < h; i++) {
        int sy = y + i;
        if (sy >= 0 && sy < (int)sh) {
            if (x >= 0 && x < (int)sw)
                bb[sy * pitch + x] = color;
            if (x + w - 1 >= 0 && x + w - 1 < (int)sw)
                bb[sy * pitch + (x + w - 1)] = color;
        }
    }
}

void boot_splash_init(void) {
    if (!g_framebuffer || !g_backbuffer)
        return;

    uint32_t sw = g_framebuffer->framebuffer_width;
    uint32_t sh = g_framebuffer->framebuffer_height;

    // 清空屏幕为深色背景
    splash_fill_rect(0, 0, sw, sh, 0xFF1A1A2E);

    // 标题
    splash_draw_text(sw / 2 - 80, 40, "MWOS Booting...", 0xFFFFFFFF);

    // 日志区边框
    int log_x = 40;
    int log_y = 80;
    int log_w = sw - 80;
    int log_h = sh - 200;
    splash_draw_rect_outline(log_x, log_y, log_w, log_h, 0xFF444466);

    g_splash_log_y = log_y + 8;
    g_splash_max_lines = log_h / 18;
    g_splash_line_count = 0;
    memset(g_splash_lines, 0, sizeof(g_splash_lines));
    memset(g_splash_colors, 0, sizeof(g_splash_colors));

    // 加载条边框
    int bar_x = log_x;
    int bar_y = log_y + log_h + 30;
    int bar_w = log_w;
    int bar_h = 20;
    splash_draw_rect_outline(bar_x, bar_y, bar_w, bar_h, 0xFF444466);
    splash_fill_rect(bar_x + 2, bar_y + 2, bar_w - 4, bar_h - 4, 0xFF222244);
}

void boot_splash_log(const char* msg, uint32_t color) {
    if (!g_framebuffer || !g_backbuffer)
        return;

    uint32_t sw = g_framebuffer->framebuffer_width;
    uint32_t sh = g_framebuffer->framebuffer_height;
    int log_w = sw - 80;
    int log_h = sh - 200;
    int log_x = 40;
    int log_y = 80;

    // 添加日志
    if (g_splash_line_count < BOOT_SPLASH_MAX_LINES) {
        strncpy(g_splash_lines[g_splash_line_count], msg,
                BOOT_SPLASH_LINE_LEN - 1);
        g_splash_colors[g_splash_line_count] = color;
        g_splash_line_count++;
    } else {
        // 滚动：丢弃最旧的一行
        for (int i = 0; i < BOOT_SPLASH_MAX_LINES - 1; i++) {
            memcpy(g_splash_lines[i], g_splash_lines[i + 1],
                   BOOT_SPLASH_LINE_LEN);
            g_splash_colors[i] = g_splash_colors[i + 1];
        }
        strncpy(g_splash_lines[BOOT_SPLASH_MAX_LINES - 1], msg,
                BOOT_SPLASH_LINE_LEN - 1);
        g_splash_colors[BOOT_SPLASH_MAX_LINES - 1] = color;
    }

    // 重绘日志区背景
    splash_fill_rect(log_x + 2, log_y + 2, log_w - 4, log_h - 4, 0xFF1A1A2E);

    // 绘制所有日志行
    int lines_to_show = g_splash_line_count;
    int start = 0;
    if (lines_to_show > g_splash_max_lines) {
        start = lines_to_show - g_splash_max_lines;
        lines_to_show = g_splash_max_lines;
    }

    for (int i = 0; i < lines_to_show; i++) {
        int idx = start + i;
        int cy = log_y + 8 + i * 18;
        splash_draw_text(log_x + 8, cy, g_splash_lines[idx],
                         g_splash_colors[idx]);
    }
}

void boot_splash_set_progress(int percent) {
    if (!g_framebuffer || !g_backbuffer)
        return;

    uint32_t sw = g_framebuffer->framebuffer_width;
    uint32_t sh = g_framebuffer->framebuffer_height;
    int log_w = sw - 80;
    int log_h = sh - 200;
    int bar_x = 40;
    int bar_y = 80 + log_h + 30;
    int bar_w = log_w;
    int bar_h = 20;

    // 重绘进度条背景
    splash_fill_rect(bar_x + 2, bar_y + 2, bar_w - 4, bar_h - 4, 0xFF222244);

    // 绘制进度
    int fill_w = (bar_w - 4) * percent / 100;
    if (fill_w > 0) {
        splash_fill_rect(bar_x + 2, bar_y + 2, fill_w, bar_h - 4, 0xFF4488FF);
    }

    // 绘制百分比文字
    char pct_str[8];
    int n = percent;
    int i = 0;
    if (n == 0) {
        pct_str[i++] = '0';
    } else {
        char tmp[8];
        int ti = 0;
        while (n > 0) {
            tmp[ti++] = '0' + (n % 10);
            n /= 10;
        }
        for (int j = ti - 1; j >= 0; j--) {
            pct_str[i++] = tmp[j];
        }
    }
    pct_str[i++] = '%';
    pct_str[i] = '\0';

    int text_x = bar_x + bar_w / 2 - (i * 8) / 2;
    int text_y = bar_y + 5;
    splash_draw_text(text_x, text_y, pct_str, 0xFFFFFFFF);
}

